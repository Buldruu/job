export const MAIN_CATS  = Object.keys(CHIGLEL_MAP);
export const getSubs    = (top) => Object.keys(CHIGLEL_MAP[top] || {});
export const getProfs   = (top, sub) => CHIGLEL_MAP[top]?.[sub] || [];
export const ALL_SUBS   = [...new Set(Object.values(CHIGLEL_MAP).flatMap(s => Object.keys(s)))];
export const ALL_PROFS  = [...new Set(Object.values(CHIGLEL_MAP).flatMap(s => Object.values(s).flat()))];

export const getMainCat = (val) => {
  for (const [top, subs] of Object.entries(CHIGLEL_MAP)) {
    if (subs[val]) return top;
    for (const profs of Object.values(subs)) {
      if (profs.includes(val)) return top;
    }
  }
  return null;
};
export const getSubCat = (prof) => {
  for (const subs of Object.values(CHIGLEL_MAP)) {
    for (const [sub, profs] of Object.entries(subs)) {
      if (profs.includes(prof)) return sub;
    }
  }
  return null;
};
